import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const githubSource = new URL('../../frontend/apps/website/public/icons/social/github.svg', import.meta.url)
const githubSourcePath = 'packages/frontend/apps/website/public/icons/social/github.svg'
const mdiCssSource = new URL('../../frontend/public/materialdesignicons.min.css', import.meta.url)
const mdiFontSource = new URL('../../frontend/public/fonts/materialdesignicons-webfont.woff2', import.meta.url)
const mdiOriginalFontFace = '@font-face{font-family:"Material Design Icons";src:url("fonts/materialdesignicons-webfont.eot?v=7.4.47");src:url("fonts/materialdesignicons-webfont.eot?#iefix&v=7.4.47") format("embedded-opentype"),url("fonts/materialdesignicons-webfont.woff2?v=7.4.47") format("woff2"),url("fonts/materialdesignicons-webfont.woff?v=7.4.47") format("woff"),url("fonts/materialdesignicons-webfont.ttf?v=7.4.47") format("truetype");font-weight:normal;font-style:normal;}'
const mdiWoff2FontFace = '@font-face{font-family:"Material Design Icons";src:url("fonts/materialdesignicons-webfont.woff2?v=7.4.47") format("woff2");font-weight:normal;font-style:normal;}'
const digest = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex')

export function normalizeMdiFontFace(css: string, font: Uint8Array): string {
  if (!css.startsWith(mdiOriginalFontFace)) throw new Error('Pinned MDI 7.4.47 font-face changed')
  if (font.byteLength <= 48 || Buffer.from(font.subarray(0, 4)).toString('ascii') !== 'wOF2')
    throw new Error('Pinned MDI WOFF2 font is missing or invalid')
  return mdiWoff2FontFace + css.slice(mdiOriginalFontFace.length)
}

async function readMdiFontFace() {
  const input = await readFile(mdiCssSource)
  const font = await readFile(mdiFontSource)
  return { input, font, output: Buffer.from(normalizeMdiFontFace(input.toString('utf8'), font)) }
}

export async function normalizeRawFrontendFontFace(outputDirectory: string): Promise<void> {
  const { input, font, output } = await readMdiFontFace()
  const cssPath = resolve(outputDirectory, 'materialdesignicons.min.css')
  if (!(await readFile(cssPath)).equals(input)) throw new Error('Raw MDI CSS differs from its pinned source')
  if (!(await readFile(resolve(outputDirectory, 'fonts/materialdesignicons-webfont.woff2'))).equals(font))
    throw new Error('Raw MDI WOFF2 differs from its pinned source')
  await writeFile(cssPath, output)
}

