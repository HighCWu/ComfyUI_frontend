export async function rawFrontendResourceIdentity() {
  const mdi = await readMdiFontFace()
  return {
    adapterSha256: digest(await readFile(new URL('./frontend-resources.ts', import.meta.url))),
    assets: (await readRawFrontendResources()).map(asset => ({
      path: asset.fileName, source: asset.sourcePath, sha256: digest(asset.source),
    })),
    fontFace: {
      profile: 'mdi-7.4.47-woff2/v1',
      source: 'packages/frontend/public/materialdesignicons.min.css',
      inputSha256: digest(mdi.input), outputSha256: digest(mdi.output),
      font: 'packages/frontend/public/fonts/materialdesignicons-webfont.woff2',
      fontSha256: digest(mdi.font),
    },
  }
}
